'use client';

import React from 'react';
import { RecentDownloadItem } from '@triattendance/shared';
import { FileSpreadsheet, Download, CheckCircle2 } from 'lucide-react';
import { Button } from '@/components/ui/button';

interface RecentDownloadsListProps {
  downloads: RecentDownloadItem[];
  onDownloadItem?: (item: RecentDownloadItem) => void;
}

export const RecentDownloadsList: React.FC<RecentDownloadsListProps> = ({
  downloads,
  onDownloadItem,
}) => {
  const handleDownload = (item: RecentDownloadItem) => {
    if (onDownloadItem) {
      onDownloadItem(item);
      return;
    }

    // Default trigger download simulation
    const dummyContent = `Report: ${item.title}\nDate: ${item.generatedDate}\nTotal Rows: ${item.rowCount}\nGenerated by TriAttendance AM Portal\n`;
    const blob = new Blob([dummyContent], { type: 'text/csv' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${item.title.toLowerCase().replace(/[^a-z0-9]/g, '_')}.csv`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="bg-white border border-gray-200 rounded-2xl p-6 shadow-sm space-y-4">
      <div className="flex items-center justify-between border-b border-gray-100 pb-3">
        <div>
          <h2 className="text-base font-bold text-gray-900 tracking-tight flex items-center gap-2">
            <FileSpreadsheet className="w-5 h-5 text-brand-600" />
            Recent Downloads
          </h2>
          <p className="text-xs text-gray-500 mt-0.5">
            Exported records generated in the last 30 days
          </p>
        </div>
        <span className="text-xs font-semibold text-gray-400">
          {downloads.length} available
        </span>
      </div>

      <div className="divide-y divide-gray-100">
        {downloads.map((item) => (
          <div
            key={item.id}
            className="py-3.5 flex items-center justify-between gap-4 first:pt-0 last:pb-0 hover:bg-gray-50/50 px-2 rounded-xl transition"
          >
            <div className="flex items-center gap-3">
              <div className="w-9 h-9 rounded-xl bg-purple-50 text-purple-700 flex items-center justify-center shrink-0">
                <FileSpreadsheet className="w-5 h-5" />
              </div>
              <div>
                <span className="text-sm font-semibold text-gray-900 block">
                  {item.title}
                </span>
                <span className="text-xs text-gray-500 flex items-center gap-2 mt-0.5">
                  <span>{item.generatedDate}</span>
                  <span>•</span>
                  <span>{item.rowCount.toLocaleString()} rows</span>
                  <span>•</span>
                  <span className="text-[10px] font-mono font-semibold px-1.5 py-0.2 bg-gray-100 text-gray-700 rounded">
                    {item.fileFormat || 'CSV'}
                  </span>
                </span>
              </div>
            </div>

            <div className="flex items-center gap-2">
              <span className="hidden sm:inline-flex items-center gap-1 text-[11px] font-medium text-emerald-700 bg-emerald-50 px-2 py-0.5 rounded-full border border-emerald-100">
                <CheckCircle2 className="w-3 h-3 text-emerald-600" />
                Ready
              </span>
              <Button
                size="sm"
                variant="outline"
                onClick={() => handleDownload(item)}
                className="gap-1.5 text-xs text-gray-700 hover:text-brand-600 font-semibold"
              >
                <Download className="w-3.5 h-3.5" />
                <span>View</span>
              </Button>
            </div>
          </div>
        ))}
      </div>
    </div>
  );
};
